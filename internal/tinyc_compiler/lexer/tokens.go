package lexer

type TokenType uint8

const (
	TOKEN_EOF TokenType = iota

	TOKEN_ASM
	TOKEN_IDENTIFIER

	TOKEN_INTEGER
	TOKEN_CHARACTER
	TOKEN_STRING

	TOKEN_VAR
	TOKEN_FUNC
	TOKEN_IF
	TOKEN_ELSE
	TOKEN_WHILE
	TOKEN_FOR
	TOKEN_DO
	TOKEN_RETURN
	TOKEN_BREAK
	TOKEN_CONTINUE

	TOKEN_PLUS
	TOKEN_MINUS
	TOKEN_STAR // Pointers not multiplication
	TOKEN_INCREMENT
	TOKEN_DECREMENT

	TOKEN_ASSIGN

	TOKEN_EQUAL
	TOKEN_NOTEQUAL
	TOKEN_LESS
	TOKEN_GREATER
	TOKEN_LESS_EQUAL
	TOKEN_GREATER_EQUAL

	TOKEN_LOGICAL_AND
	TOKEN_LOGICAL_OR
	TOKEN_LOGICAL_NOT
	TOKEN_AMPERSAND // TOKEN_BITWISE_AND
	TOKEN_BITWISE_OR
	TOKEN_BITWISE_XOR
	TOKEN_BITWISE_NOT
	TOKEN_SHIFT_LEFT
	TOKEN_SHIFT_RIGHT

	TOKEN_SEMICOLON
	TOKEN_COMMA
	TOKEN_LPAREN
	TOKEN_RPAREN
	TOKEN_LBRACE
	TOKEN_RBRACE
	TOKEN_LBRACKET
	TOKEN_RBRACKET
)

type Token struct {
	Type   TokenType
	Value  string
	Line   int
	Column int
}

var Keywords = map[string]TokenType{
	"asm":      TOKEN_ASM,
	"var":      TOKEN_VAR,
	"func":     TOKEN_FUNC,
	"if":       TOKEN_IF,
	"else":     TOKEN_ELSE,
	"while":    TOKEN_WHILE,
	"for":      TOKEN_FOR,
	"return":   TOKEN_RETURN,
	"break":    TOKEN_BREAK,
	"continue": TOKEN_CONTINUE,
}

var Punctuation = map[byte]TokenType{
	';': TOKEN_SEMICOLON,
	',': TOKEN_COMMA,
	'(': TOKEN_LPAREN,
	')': TOKEN_RPAREN,
	'{': TOKEN_LBRACE,
	'}': TOKEN_RBRACE,
	'[': TOKEN_LBRACKET,
	']': TOKEN_RBRACKET,
}

var Operators = map[string]TokenType{
	"+":  TOKEN_PLUS,
	"++": TOKEN_INCREMENT,

	"-":  TOKEN_MINUS,
	"--": TOKEN_DECREMENT,

	"*": TOKEN_STAR,

	"=":  TOKEN_ASSIGN,
	"==": TOKEN_EQUAL,

	"!":  TOKEN_LOGICAL_NOT,
	"!=": TOKEN_NOTEQUAL,

	"<":  TOKEN_LESS,
	"<=": TOKEN_LESS_EQUAL,
	"<<": TOKEN_SHIFT_LEFT,

	">":  TOKEN_GREATER,
	">=": TOKEN_GREATER_EQUAL,
	">>": TOKEN_SHIFT_RIGHT,

	"&":  TOKEN_AMPERSAND,
	"&&": TOKEN_LOGICAL_AND,

	"|":  TOKEN_BITWISE_OR,
	"||": TOKEN_LOGICAL_OR,

	"^": TOKEN_BITWISE_XOR,
	"~": TOKEN_BITWISE_NOT,
}
